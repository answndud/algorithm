def solution(jobs):
    import heapq
    
    jobs.sort(key=lambda x: x[0])
    heap = []
    time = 0
    total = 0
    i = 0
    n = len(jobs)
    
    # 모든 작업이 처리될 때까지
    while i < n or heap:
        # 현재 시간까지 들어온 작업들을 힙에 추가
        while i < n and jobs[i][0] <= time:
            # 힙에 (소요시간, 요청시간) 넣기
            heapq.heappush(heap, (jobs[i][1], jobs[i][0]))
            i += 1
        # 힙에 작업이 있으면 처리
        if heap:
            length, start = heapq.heappop(heap)
            time += length
            total += time - start
        else:
            # 없으면 다음 작업 요청시간으로 이동
            time = jobs[i][0]
    # 평균 반환 (소수점 버림)
    return total // n


