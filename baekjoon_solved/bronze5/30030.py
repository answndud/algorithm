# A = B / 1.1 입니다. 이를 분수로 표현하면 A = B * (10 / 11) 입니다.
# 또는 A = B - VAT(부가가치세) 입니다.
#
# VAT는 A의 10% 이므로, VAT = A * 0.1 입니다.
# 이 두 식을 결합하면, VAT = (B * (10/11)) * 0.1 = B / 11 이 됩니다.
# 즉, 부가가치세 금액은 최종 가격 B를 11로 나눈 값입니다.
#
# 따라서, 원래 가격 A는 최종 가격 B에서 부가가치세 금액(B/11)을 뺀 값입니다.
# A = B - (B / 11)
# B가 11의 배수이므로 정수 나눗셈(//)을 사용해도 정확한 VAT 금액이 나옵니다.

# ======================================== #

b = int(input())
a = (b * 10) // 11
print(a)

# 부가가치세(10%)가 포함된 가격 B는 원래 가격 A의 1.1배입니다.
# B = A * 1.1
# 따라서, 원래 가격 A는 B를 1.1로 나눈 값입니다.
# A = B / 1.1
#
# 분수 형태로 나타내면, A = B / (11 / 10) = B * (10 / 11) 입니다.
# 이 코드는 최종 가격 B에 (10 / 11)을 곱하여 원래 가격 A를 구하는 과정입니다.
# (b * 10)을 먼저 계산한 후, 정수 나눗셈(//)으로 11을 나누어 정확한 정수 A를 얻습니다.