'''
1) Dynamic Programming(DP)이 뭔가

DP는 큰 문제를 작은 부분 문제로 쪼개서, 그 부분 문제의 답을 한 번만 계산해 저장하고, 이를 이용해 큰 문제의 답을 구하는 기법입니다.

핵심은 두 가지 조건입니다.

- 최적 부분 구조(Optimal Substructure)
    큰 문제의 최적해가, 부분 문제들의 최적해로부터 만들어진다.
    예: 최단 경로, 최대 합, 최소 비용 등.

- 중복 부분 문제(Overlapping Subproblems)
    같은 부분 문제가 여러 번 반복해서 등장한다.
    예: 피보나치에서 F(5)를 구하려고 F(4), F(3)을 구하고, F(4)를 구하려고 또 F(3), F(2)를 구함.

이 두 조건이 충족되면 DP로 시간 복잡도를 크게 줄일 수 있습니다.


2) DP가 필요한 문제의 “신호” 
코딩테스트에서 다음 단어/구조가 나오면 DP 가능성이 큽니다.
    - “최대/최소”, “경로 수”, “가능/불가능”, “최적”, “경우의 수”
    - 배열/격자에서 누적하며 최적값 갱신
    - 선택/비선택이 반복되는 구조 (부분집합, 배낭, 집 털기 등)
    - 문자열 비교(편집 거리, LCS)처럼 접두사/부분 문자열 기반
    - “N이 크고” 완전탐색은 터질 것 같을 때
    - 재귀로 풀면 같은 상태가 반복 호출되는 형태


3) DP 풀이의 표준 접근법 (이 순서대로 하면 됨)
    Step 0. 상태(State) 정의: “부분 문제”를 무엇으로 정의할지 결정합니다. 보통 dp[i], dp[i][j], dp[i][mask] 같은 형태.
        - 1차원 DP: 인덱스 i까지의 
        - 2차원 DP: i, j 두 축(문자열, 격자, 구간 등)
        - 비트마스크 DP: 방문 집합(외판원 등)

    Step 1. dp가 의미하는 바를 한국어로 정확히 문장화
        예:
        - dp[i] = i번째 원소까지 고려했을 때 가능한 최대 합
        - dp[i][j] = s의 앞 i글자와 t의 앞 j글자의 LCS 길이
        이 문장이 애매하면 이후 전이가 무너집니다.
    
    Step 2. 점화식(전이, Transition) 세우기
        dp[state]가 dp[smaller_state]로부터 어떻게 오는지.

        전이에서 자주 나오는 형태:
        - 마지막 선택을 기준으로 분해: “마지막으로 무엇을 했는가?”를 기준으로 케이스 나누기.
        - 현재 선택/비선택 예: take / skip

    Step 3. 초기값(Base case)
        - 가장 작은 상태에서의 답.
        예: dp[0] = 0, dp[1] = ... 혹은 dp[0][*], dp[*][0]

    Step 4. 계산 순서(Top-down vs Bottom-up)
        - Top-down(메모이제이션): 재귀 + 캐시: 구현 빠르고 직관적. 단, 파이썬은 재귀 깊이/속도 주의.
        - Bottom-up(테이블): 반복문으로 작은 것부터 채우기: 실행 안정적이고 최적화(공간 줄이기)에 유리.

    Step 5. 정답 추출
        - dp[n]인지, max(dp[n][*])인지, 마지막에 뭘 출력해야 하는지.

4) 반드시 익혀야 하는 DP 기본 패턴 6개
    (A) 1차원 누적 최적: 피보나치/계단/최대 부분합
        dp[i]가 dp[i-1], dp[i-2] 등 이전 몇 개로 결정

    (B) 선택/비선택: 배낭(0/1 Knapsack), 집 털기
        dp[i] = max(dp[i-1], dp[i-2] + value[i]) 같은 형태

    (C) 2차원 격자: 최단/최대 경로, 경우의 수
        dp[r][c] = ... from dp[r-1][c], dp[r][c-1]

    (D) 문자열 DP: LCS, 편집 거리
        접두사 기준: dp[i][j]

    (E) 구간 DP: 행렬 곱 최적화, 파일 합치기
        dp[l][r] = min(dp[l][k] + dp[k+1][r] + cost)
        계산 순서가 중요(구간 길이 증가)

    (F) 상태 압축/비트마스크 DP: TSP, 방문 집합
        dp[mask][i] = mask 상태에서 i에서 끝나는 최적
        
9) DP를 “잘못 푸는” 대표 원인과 체크리스트
    (1) 상태 정의가 틀림
        “dp[i]가 뭘 의미하지?”를 정확히 문장으로 못 쓰면 위험 신호

    (2) 전이가 누락됨
        “마지막 행동” 기준으로 케이스를 전부 나눴는지 확인
        예: 마지막을 선택한 경우/안 한 경우

    (3) 초기값이 틀림
        dp[0]을 0으로 둘지 1로 둘지(경우의 수는 종종 1)

    (4) 계산 순서가 틀림
        0/1 배낭에서 w를 증가 방향으로 돌리는 실수
        구간 DP에서 길이 증가 순서를 지키지 않음

    (5) 시간/공간 터짐
        상태 수가 N^2인데 N=20000이면 불가능
        dp 2차원 배열 대신 1차원 롤링 가능한지 확인
        
10) 실전에서 DP를 빨리 떠올리는 훈련 루틴
    1. 브루트포스/재귀로 먼저 설계 (가능하면)
    2. 중복 호출되는 “상태”가 뭔지 찾아서 캐싱 포인트로 삼기
    3. 그 상태가 i, i,j, i,w 등으로 정리되는지 본다
    4. 메모이제이션(top-down)으로 먼저 통과 → 이후 바텀업/최적화
    초보 단계에서는 Top-down이 사고 흐름을 만들기 쉬운 편이고, 이후 바텀업으로 “정석 구현”을 익히는 게 효율적입니다.
'''

# 예제1. 피보나치 / 포인트: dp[i]는 dp[i-1], dp[i-2]만 필요 → 배열이 필요 없을 수 있음.
def fib1(n: int) -> int: # Botton Up 방식
    if n <= 1: return n
    dp = [0] * (n + 1)
    dp[1] = 1
    for i in range(2, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]
    return dp[n]

def fib2(n: int) -> int: # 공간 최적화 O(1)
    if n <= 1: return n
    a, b = 0, 1
    for _ in range(2, n + 1):
        a, b = b, a + b
    return b


# 예제 2: 계단 오르기(BOJ 2579류 변형) 느낌의 기본
# 문제(대표 형태): 한 번에 1칸 또는 2칸 오를 수 있을 때, n칸에 도달하는 경우의 수.
# 점화식: dp[i] = dp[i-1] + dp[i-2],  dp[0]=1(아무것도 안 하고 0칸 도달 1가지), dp[1]=1
# 주의: 경우의 수 DP는 base case를 어떻게 두느냐에 따라 전체가 바뀝니다. dp[0]=1은 매우 자주 쓰이는 트릭입니다.
def count_ways(n: int) -> int:
    dp = [0] * (n + 1)
    dp[0] = 1
    if n >= 1:
        dp[1] = 1
    for i in range(2, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]
    return dp[n]

# 예제 3: 0/1 Knapsack (선택/비선택의 정석)
# 문제: 무게 제한 W, 각 물건 (weight, value). 물건을 한 번씩만 선택 가능. 최대 가치. 
# 상태
# : dp[w] = 현재까지 고려한 물건들로 무게 w에서의 최대 가치 전이
# 물건 (wt, val)을 넣으면: dp[w] = max(dp[w], dp[w-wt] + val) 
# 0/1이므로 w를 큰 쪽에서 작은 쪽으로 내려가며 갱신(중복 선택 방지)
def knapsack_01(items, W: int) -> int:
    dp = [0] * (W + 1)
    for wt, val in items:
        for w in range(W, wt - 1, -1):
            dp[w] = max(dp[w], dp[w - wt] + val)
    return dp[W]

# 예제 4: LCS (문자열 DP의 대표)
# 문제: 두 문자열 s, t의 최장 공통 부분수열 길이.
# 상태: dp[i][j] = s의 앞 i글자와 t의 앞 j글자의 LCS 길이
# 전이: s[i-1] == t[j-1] → dp[i][j] = dp[i-1][j-1] + 1, else → dp[i][j] = max(dp[i-1][j], dp[i][j-1])
def lcs_len(s: str, t: str) -> int:
    n, m = len(s), len(t)
    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            if s[i - 1] == t[j - 1]:
                dp[i][j] = dp[i - 1][j - 1] + 1
            else:
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])
    return dp[n][m]


